def profile_path(directory):
    raw = directory/"rank_profiles.jsonl"
    packed = directory/"rank_profiles.jsonl.gz"
    if raw.exists():
        return raw
    if packed.exists():
        return packed
    raise FileNotFoundError(
        "missing rank_profiles.jsonl(.gz); the executable may be stale or profiling was not enabled")

@contextmanager
def run_guard(directory):
    """Share the runner's lock so analysis never cleans an active run."""
    lock = directory/".run.lock"
    fd = os.open(lock, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "w") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            yield False
        else:
            try:
                yield True
            finally:
                fcntl.flock(handle, fcntl.LOCK_UN)

def compress_result(path):
    """Atomic, lossless compression; keep the source if anything fails."""
    target = path.with_name(path.name + ".gz")
    if not path.is_file() or path.is_symlink() or target.is_symlink():
        return 0
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".compress-", delete=False) as out:
            temporary = Path(out.name)
            with path.open("rb") as source, gzip.GzipFile(filename="", mode="wb", fileobj=out, mtime=0) as packed:
                shutil.copyfileobj(source, packed, 1024 * 1024)
        saved = path.stat().st_size - temporary.stat().st_size
        if saved <= 0:
            return 0
        os.replace(temporary, target)
        path.unlink()
        return saved
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)

# Only files generated by this program, directly inside a finished run's mesh/.
# Never derive a deletion path from profile metadata or scan the entire repository.
MESH_OUTPUTS = {
    "test_occ": r"test_occ\.vol",
    "refinedSurfmesh": r"refinedSurfmesh[0-9]+\.vol",
    "volfined": r"volfined[0-9]+\.vol",
    "volwithadj": r"volwithadj[0-9]+\.vol",
}

def cleanup_run(directory):
    """Caller holds run_guard and has validated the successful core-only profile."""
    removed = freed = compressed = 0
    mesh = directory/"mesh"
    if mesh.is_dir() and not mesh.is_symlink():
        for folder in mesh.iterdir():
            if not folder.is_dir() or folder.is_symlink():
                continue
            pattern = MESH_OUTPUTS.get(folder.name)
            if re.fullmatch(r"partitioning\.[0-9]+", folder.name):
                pattern = r"part\.[0-9]+\.(nodes|elements|boundary|header|shared)"
            if pattern:
                for path in folder.iterdir():
                    if path.is_file() and not path.is_symlink() and re.fullmatch(pattern, path.name):
                        size = path.stat().st_size
                        path.unlink()
                        freed += size
                        removed += 1
            if pattern or folder.name in ("meshQuality", "testout"):
                if not any(folder.iterdir()):
                    folder.rmdir()
        if not any(mesh.iterdir()):
            mesh.rmdir()
    for name in ("rank_profiles.jsonl", "run.log"):
        compressed += compress_result(directory/name)
    return removed, freed, compressed

def try_cleanup(directory):
    try:
        return cleanup_run(directory)
    except OSError as error:
        # Disk/permission failures in housekeeping must not invalidate a valid measurement.
        print(f"Cleanup warning ({directory}): {error}", file=sys.stderr)
        return 0, 0, 0

def mean(x):
    return st.fmean(x) if x else 0.0

def corr(a, b):
    if len(a) < 2:
        return None
    av, bv = mean(a), mean(b)
    xx = sum((x-av)**2 for x in a)
    yy = sum((y-bv)**2 for y in b)
    return sum((x-av)*(y-bv) for x, y in zip(a, b))/math.sqrt(xx*yy) if xx*yy else None

def seconds(row, name):
    return row["stages"].get(name, {}).get("seconds", 0.0)

def inspect(path, sample_sink=None):
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt") as stream:
        rows = [json.loads(line) for line in stream if line.strip()]
    if not rows:
        raise ValueError("empty rank profiles")
    n = rows[0]["ranks"]
    if len(rows) != n or sorted(r["rank"] for r in rows) != list(range(n)):
        raise ValueError("missing or duplicate rank rows")
    metadata = rows[0]["metadata"]
    for r in rows:
        if r["ranks"] != n or r["repeat"] != rows[0]["repeat"] or r["metadata"] != metadata:
            raise ValueError("inconsistent run metadata")
        if not math.isfinite(r["metrics"]["core_seconds"]) or r["metrics"]["core_seconds"] <= 0:
            raise ValueError("invalid core time")
    if metadata.get("core_only") != "true":
        raise ValueError("performance comparison requires core_only=true")
    compute = [sum(seconds(r, stage) for stage in COMPUTE) for r in rows]
    waiting = [seconds(r, "vertex_count_pre_collective_wait") for r in rows]
    tets = [r["metrics"].get("local_volume_elements_before_adjacency", 0) for r in rows]
    predicted = [r["metrics"].get("predicted_cost_after", 0) for r in rows]
    names = sorted({name for r in rows for name in r["stages"]})
    detail = []
    for name in names:
        times = [seconds(r, name) for r in rows]
        detail.append(dict(stage=name, mean_seconds=mean(times), max_seconds=max(times),
                           calls_sum=sum(r["stages"].get(name, {}).get("calls", 0) for r in rows)))
    face_bytes = sum(s.get("receive_bytes", 0) for r in rows for name, s in r["stages"].items()
                     if name == "face_allgatherv" or name.startswith("face_sparse_"))
    split = metadata["timing_mode"] == "split"
    result = dict(algorithm=metadata["algorithm"], timing=metadata["timing_mode"], ranks=n,
                  partition_seed=int(metadata.get("partition_seed",-1)),
                  repeat=rows[0]["repeat"], core_seconds=max(r["metrics"]["core_seconds"] for r in rows),
                  face_pipeline_seconds=max(seconds(r, "face_pipeline_total") for r in rows),
                  face_exchange_seconds=max(sum(s["seconds"] for name, s in r["stages"].items()
                      if name in ("face_allgatherv", "face_sparse_match", "face_sparse_directory", "face_sparse_deliver")) for r in rows),
                  vertex_wait_seconds=max(waiting) if split else None,
                  compute_imbalance=max(compute)/mean(compute) if mean(compute) else None,
                  element_imbalance=max(tets)/mean(tets) if mean(tets) else None,
                  volume_elements_sum=sum(tets), face_payload_receive_bytes=face_bytes,
                  predicted_actual_correlation=corr(predicted, compute),
                  compute_wait_correlation=corr(compute, waiting) if split else None,
                  # Root-only global partition diagnostics.
                  cut_before=max(r["metrics"].get("partition_cut_before", 0) for r in rows),
                  cut_after=max(r["metrics"].get("partition_cut_after", 0) for r in rows),
                  partition_moves=max(r["metrics"].get("partition_moves", 0) for r in rows))
    if metadata.get("feature_schema") in ("mesh_phase_v2", "mesh_phase_v3"):
        # Validate even during --finish-run, before SUCCESS is written.
        samples=[]
        bundle_map={}; logical_seen=set()
        features=14 if metadata["feature_schema"]=="mesh_phase_v3" else 8
        for r in rows:
            sample={k:metadata.get(k, "unset") for k in SAMPLE_META}
            sample["partition_seed"]=result["partition_seed"]
            sample["processor_name"]=r.get("processor_name","unset")
            sample["logical_partition"]=int(r["metrics"].get("logical_partition",r["rank"]))
            sample["volume_elements"]=r["metrics"].get("local_volume_elements_before_adjacency",0)
            if metadata.get("sampling_protocol")=="partition_sampling_v1":
                shift=int(metadata["rank_shift"]);logical=sample["logical_partition"]
                if metadata.get("balance_method")=="node_mapping":
                    rpn=int(metadata["RANKS_PER_NODE"])
                    if rpn<=0 or n%rpn or shift%rpn or not 0<=shift<n or not 0<=logical<n or logical in logical_seen:
                        raise ValueError("invalid node bundle permutation")
                    logical_seen.add(logical)
                    bundle,target=logical//rpn,r["rank"]//rpn
                    if logical%rpn!=r["rank"]%rpn or bundle_map.get(bundle,target)!=target:
                        raise ValueError("node bundle was split")
                    bundle_map[bundle]=target
                elif not 0<=logical<n or not 0<=shift<n or (logical+shift)%n!=r["rank"]:
                    raise ValueError("logical partition/physical rank mapping mismatch")
            sample.update(algorithm=metadata["algorithm"], ranks=n, rank=r["rank"], repeat=r["repeat"])
            sample.update({f"x{k}":r["metrics"][f"phase_feature_{k}"] for k in range(features)})
            sample.update({f"y{k}":sum(seconds(r, s) for s in phase) for k,phase in enumerate(PHASES)})
            for key in ("face_complete_elapsed", "vertex_arrival_elapsed"):
                sample[key]=r["metrics"][key]
            numeric=[sample[f"x{k}"] for k in range(features)]+[sample[f"y{k}"] for k in range(4)]+[
                sample["face_complete_elapsed"],sample["vertex_arrival_elapsed"]]
            if any(not math.isfinite(v) or v<0 for v in numeric):
                raise ValueError("invalid phase sample")
            if sample["vertex_arrival_elapsed"]<sample["face_complete_elapsed"]:
                raise ValueError("invalid within-rank event order")
            if sample["vertex_arrival_elapsed"]>r["metrics"]["core_seconds"]+1e-6:
                raise ValueError("event endpoint exceeds core interval")
            if any(r["stages"].get(s, {}).get("calls", 0)!=1 for s in COMPUTE):
                raise ValueError("phase model requires one complete call of each compute stage")
            samples.append(sample)
        if bundle_map and len(set(bundle_map.values()))!=len(bundle_map):
            raise ValueError("node bundle mapping is not bijective")
        face_end=[r["metrics"]["face_complete_elapsed"] for r in rows]
        arrival=[r["metrics"]["vertex_arrival_elapsed"] for r in rows]
        result.update(compute_max_seconds=max(compute), compute_mean_seconds=mean(compute),
                      vertex_wait_mean_seconds=mean(waiting) if split else None,
                      face_completion_spread=max(face_end)-min(face_end),
                      vertex_arrival_spread=max(arrival)-min(arrival),
                      post_face_compute_max_seconds=max(b-a for a,b in zip(face_end,arrival)),
                      face_completion_wait_correlation=corr(face_end,waiting) if split else None)
        for key in ("partition_adopted", "partition_proposed_moves", "closure_total_before", "closure_total_after",
                    "closure_max_before", "closure_max_after", "candidate_closure_total", "candidate_closure_max",
                    "seed_max_seconds", "candidate_max_seconds", "partition_rejection_flags",
                    "seed_lower_seconds", "candidate_upper_seconds", "net_gain_lower_seconds",
                    "correction_seconds", "search_timed_out", "search_skipped",
                    "mapping_moved_nodes", "mapping_predicted_gain_seconds"):
            result[key]=next(r for r in rows if r["rank"]==0)["metrics"].get(key,0)
        for s in ("metis_partition", "partition_cost_setup", "partition_cost_balance", "partition_node_mapping"):
            result[s+"_seconds"]=max(seconds(r,s) for r in rows)
        for k in range(4):
            actual=[s[f"y{k}"] for s in samples]
            result[f"phase_{k}_max_seconds"]=max(actual)
            result[f"phase_{k}_prediction_wape"]=(sum(abs(r["metrics"][f"phase_prediction_{k}"]-a)
                for r,a in zip(rows,actual))/sum(actual) if metadata["cost_model"].startswith("phase_seconds") and sum(actual)>0 else None)
        if sample_sink is not None and not split and rows[0]["repeat"]>0:
            sample_sink.writerows(samples)
    return result, detail

def write_csv(path, rows):
    if not rows:
        return
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

def expected_runs(root):
    total = 0
    for path in root.rglob("plan.json"):
        plan = json.loads(path.read_text())
        total += plan["repeats"] * len(plan["algorithms"]) * len(plan["timings"]) * len(plan.get("partition_seeds",[-1]))
    return total

def compact(value, digits=3):
    if value is None:
        return "-"
    return f"{value:.{digits}f}"

def write_overview(root, runs, summaries, errors):
    """One human-facing result file; CSV files remain machine-readable details."""
    expected = expected_runs(root)
    complete = len(runs) == expected and not errors
    readiness=sampling_readiness(root)
    if readiness is not None:
        (root/"analysis/calibration_status.json").write_text(json.dumps(readiness,ensure_ascii=False,indent=2)+"\n")
    lines = [
        "实验结果总览 / Experiment result overview",
        "=" * 56,
        f"状态: {'完整，可分析' if complete else '不完整，不可直接比较'}",
        f"有效正式运行: {len(runs)} / {expected}",
        f"异常项: {len(errors)}",
        *( ["校准可用性: "+("通过采样检查" if readiness["ready"] else "未通过，不能进入评价"),
            "说明: "+readiness["message"]] if readiness is not None else [] ),
        "",
        "优先查看：",
        "1. 本文件：快速判断实验是否完整及主要指标。",
        "2. analysis/summary.csv：论文分析用的重复实验中位数。",
        "3. analysis/issues.txt：仅在异常项不为 0 时查看。",
        "4. repeat_*/run.log.gz：只在排查某次失败时查看。",
        "",
        "核心汇总（时间单位 s，通信量单位 GiB）：",
        "algorithm timing ranks seed repeats core compute_max face_exchange vertex_wait imbalance recv_GiB vs_baseline vs_sparse",
    ]
    for row in summaries:
        received = row.get("face_payload_receive_bytes_median")
        lines.append(" ".join((
            str(row["algorithm"]), str(row["timing"]), str(row["ranks"]),
            str(row["partition_seed"]),
            str(row["successful_repeats"]), compact(row["core_median"]),
            compact(row.get("compute_max_seconds_median")),
            compact(row.get("face_exchange_seconds_median")),
            compact(row.get("vertex_wait_seconds_median")),
            compact(row.get("compute_imbalance_median")),
            compact(received/(1024**3) if received is not None else None),
            compact(row.get("speedup_vs_baseline")), compact(row.get("speedup_vs_sparse")),
        )))
        if row["algorithm"] in ("balance","combined"):
            if row.get("mapping_moved_nodes_median",0):
                lines.append("  节点映射：移动节点数="+compact(row["mapping_moved_nodes_median"])+
                             "；预测收益="+compact(row.get("mapping_predicted_gain_seconds_median"))+" s（非实测加速）")
            lines.append("  分区诊断：采用比例="+compact(row.get("adoption_rate"))+
                         "；跳过搜索次数="+str(row.get("skipped_runs",0))+
                         "；拒绝原因计数="+str(row.get("rejection_counts","{}")))
    for capacity in sorted(root.glob("**/node_capacities.json")):
        report=json.loads(capacity.read_text())
        lines.append(f"节点能力准备 {capacity.parent.name}: {report['setup_wall_seconds']:.3f} s；"
                     f"最慢/最快因子={report['slowdown_ratio']:.3f}；一次预热成本单列，不能视为免费。")
    if errors:
        lines += ["", "存在异常：请先查看 analysis/issues.txt，不能直接使用本批结果。"]
    (root/"RESULT_SUMMARY.txt").write_text("\n".join(lines)+"\n")
    return expected, complete

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path)
    parser.add_argument("--keep-artifacts", action="store_true", help="skip mesh cleanup and lossless compression")
    parser.add_argument("--finish-run", action="store_true", help="runner: validate one completed run, then retain its measurements")
    parser.add_argument("--require-calibration",action="store_true",help="采样完整后还必须通过分区多样性与节点轮换检查")
    args = parser.parse_args()
    if args.finish_run:
        try:
            with run_guard(args.root) as acquired:
                if not acquired or (args.root/"RUNNING").exists():
                    raise ValueError("run is still active; finalization skipped")
                inspect(profile_path(args.root))
                (args.root/"SUCCESS").touch()
                if not args.keep_artifacts:
                    try_cleanup(args.root)
        except (OSError, EOFError, ValueError, KeyError, TypeError) as error:
            print(f"Invalid completed run ({args.root}): {error}", file=sys.stderr)
            raise SystemExit(1)
        return
    runs, stage_rows, errors = [], [], []
    output = args.root/"analysis"
    output.mkdir(exist_ok=True)
    sample_tmp=output/"model_samples.csv.gz.tmp"
    sample_stream=gzip.open(sample_tmp, "wt", newline="")
    sample_writer=csv.DictWriter(sample_stream,fieldnames=SAMPLE_FIELDS)
    sample_writer.writeheader()
    completed = []
    directories = {p.parent for pattern in ("rank_profiles.jsonl", "rank_profiles.jsonl.gz") for p in args.root.rglob(pattern)}
    for directory in sorted(directories):
        try:
            with run_guard(directory) as acquired:
                if not acquired or (directory/"RUNNING").exists():
                    errors.append(f"Active run, skipped: {directory}")
                    continue
                if not (directory/"SUCCESS").exists():
                    errors.append(f"Incomplete run: {directory}")
                    continue
                result, details = inspect(profile_path(directory), sample_writer)
            completed.append(directory)
            if result["repeat"] <= 0:
                continue  # Explicit warmups; no subtraction/estimated timing.
            runs.append(result)
            for detail in details:
                identity = {k: result[k] for k in ("algorithm", "timing", "ranks", "partition_seed", "repeat")}
                identity.update(detail)
                stage_rows.append(identity)
        except (OSError, EOFError, ValueError, KeyError, TypeError) as error:
            errors.append(f"{directory}: {error}")
    present_runs = {(r["algorithm"], r["timing"], r["ranks"], r["partition_seed"], r["repeat"]) for r in runs}
    if len(present_runs)!=len(runs): errors.append("Duplicate run identity (algorithm, timing, ranks, seed, repeat)")
    for plan_path in args.root.rglob("plan.json"):
        plan = json.loads(plan_path.read_text())
        for algorithm in plan["algorithms"]:
            for timing in plan["timings"]:
                for seed in plan.get("partition_seeds",[-1]):
                    missing = [rep for rep in range(1, plan["repeats"]+1)
                               if (algorithm, timing, plan["ranks"], seed, rep) not in present_runs]
                    if missing:
                        errors.append(f"Missing measured repeats: p{plan['ranks']} seed={seed} {algorithm}/{timing}: {missing}")
    groups = defaultdict(list)
    for run in runs:
        groups[run["algorithm"], run["timing"], run["ranks"], run["partition_seed"]].append(run)
    summaries = []
    for (algorithm, timing, ranks, seed), group in sorted(groups.items()):
        values = [r["core_seconds"] for r in group]
        summary = dict(algorithm=algorithm, timing=timing, ranks=ranks, partition_seed=seed, successful_repeats=len(group),
                       core_median=st.median(values), core_cv=st.stdev(values)/mean(values) if len(values)>1 else None)
        for name in runs[0]:
            if name in ("algorithm", "timing", "ranks", "partition_seed", "repeat", "core_seconds"):
                continue
            present = [r[name] for r in group if r.get(name) is not None]
            summary[name+"_median"] = st.median(present) if present else None
        base = groups.get(("baseline", timing, ranks, seed))
        summary["speedup_vs_baseline"] = st.median(r["core_seconds"] for r in base)/summary["core_median"] if base else None
        sparse=groups.get(("sparse",timing,ranks,seed))
        summary["speedup_vs_sparse"] = st.median(r["core_seconds"] for r in sparse)/summary["core_median"] if sparse else None
        summary["adoption_rate"]=mean([r.get("partition_adopted",0) for r in group])
        summary["skipped_runs"]=sum(r.get("search_skipped",0) for r in group)
        reasons={1:"nominal_gain",2:"total_closure",4:"max_closure",8:"no_moves",16:"error_or_net_gain",32:"feature_range"}
        summary["rejection_counts"]=json.dumps({name:sum(bool(int(r.get("partition_rejection_flags",0))&bit) for r in group)
            for bit,name in reasons.items()},sort_keys=True)
        summaries.append(summary)
    # Failures are retained even when the driver continued to later experiments.
    for path in args.root.rglob("run_status.tsv"):
        with path.open() as f:
            latest = {}
            for row in csv.DictReader(f, delimiter="\t"):
                latest[row["directory"]] = row
            errors.extend(f"Failed run (exit {r['exit_code']}): {r['directory']}" for r in latest.values() if r["exit_code"] != "0")
    requested = args.root/"requested_process_counts.txt"
    if requested.exists():
        present = {r["ranks"] for r in runs}
        errors.extend(f"No successful measured runs for p{n}" for n in map(int, requested.read_text().split()) if n not in present)
    output = args.root/"analysis"
    output.mkdir(exist_ok=True)
    write_csv(output/"runs.csv", runs)
    write_csv(output/"stages.csv", stage_rows)
    write_csv(output/"summary.csv", summaries)
    (output/"issues.txt").write_text("\n".join(errors)+( "\n" if errors else ""))
    sample_stream.close()
    if any("compute_max_seconds" in r for r in runs):
        os.replace(sample_tmp,output/"model_samples.csv.gz")
    else:
        sample_tmp.unlink()
    expected, complete = write_overview(args.root, runs, summaries, errors)
    print(f"RESULT: {len(runs)}/{expected} measured runs, {len(errors)} issues; read {args.root/'RESULT_SUMMARY.txt'}")
    if args.require_calibration:
        path=output/"calibration_status.json"
        if not complete or not path.exists() or not json.loads(path.read_text())["ready"]:
            raise SystemExit("采样检查未通过，请查看 RESULT_SUMMARY.txt；已完成的测量保留")
    if not runs:
        raise SystemExit(1)
    # Reporting succeeds before deletion. Recheck under the lock: a resumed job
    # may have started while the analyzer was writing the aggregate CSV files.
    if not args.keep_artifacts:
        for directory in completed:
            try:
                with run_guard(directory) as acquired:
                    if acquired and not (directory/"RUNNING").exists() and (directory/"SUCCESS").exists():
                        inspect(profile_path(directory))
                        try_cleanup(directory)
            except (OSError, EOFError, ValueError, KeyError, TypeError) as error:
                print(f"Cleanup skipped ({directory}): {error}", file=sys.stderr)

if __name__ == "__main__":
    main()
